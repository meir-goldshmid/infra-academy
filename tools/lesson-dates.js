// Writes content/lesson-dates.js: the date each lesson's text last changed, from git blame.
// Usage: node tools/lesson-dates.js         (rewrite the file)
//        node tools/lesson-dates.js --check (exit 1 if the file is out of date)
// Run it before every publish (the /publish skill does). The app shows "Updated <date>" and
// flags lessons not touched in 12+ months as "may be outdated" (fix with /refresh <lesson-id>).
const fs = require("fs");
const path = require("path");
const vm = require("vm");
const { execFileSync } = require("child_process");

const root = path.join(__dirname, "..");
const OUT = path.join(root, "content", "lesson-dates.js");
const files = fs.readdirSync(path.join(root, "content")).filter(f => f.endsWith(".js") && f !== "lesson-dates.js" && f !== "refs.js");
const todayISO = new Date().toISOString().slice(0, 10);
const dates = {};

for (const f of files) {
  const rel = "content/" + f;
  const src = fs.readFileSync(path.join(root, rel), "utf8");
  // which lesson ids does this file define?
  const sb = {}; sb.window = sb; vm.createContext(sb);
  try { vm.runInContext(src, sb); } catch (e) { continue; }
  const ids = ((sb.INFRA || {}).lessons || []).map(l => l.id);
  if (!ids.length) continue;
  // per-line commit date (uncommitted lines count as today)
  let lineDates = [];
  try {
    const out = execFileSync("git", ["blame", "--line-porcelain", rel], { cwd: root, encoding: "utf8", maxBuffer: 256 * 1024 * 1024 });
    let cur = null;
    for (const ln of out.split("\n")) {
      if (/^[0-9a-f]{40} /.test(ln)) cur = { hash: ln.slice(0, 40) };
      else if (ln.startsWith("committer-time ")) cur.time = +ln.slice(15);
      else if (ln.startsWith("\t")) lineDates.push(/^0{40}$/.test(cur.hash) ? todayISO : new Date(cur.time * 1000).toISOString().slice(0, 10));
    }
  } catch (e) { lineDates = src.split("\n").map(() => todayISO); } // not committed yet
  const lines = src.split("\n");
  const starts = ids.map(id => ({ id, at: lines.findIndex(s => new RegExp(`^\\s*id:\\s*["']${id.replace(/[-]/g, "\\-")}["']`).test(s)) }))
    .filter(x => x.at >= 0).sort((a, b) => a.at - b.at);
  starts.forEach((s, i) => {
    const end = i + 1 < starts.length ? starts[i + 1].at : lines.length;
    let max = "";
    for (let k = Math.max(0, s.at - 3); k < end; k++) if (lineDates[k] && lineDates[k] > max) max = lineDates[k];
    dates[s.id] = max || todayISO;
  });
}

const sorted = Object.fromEntries(Object.keys(dates).sort().map(k => [k, dates[k]]));
const body = `// GENERATED by tools/lesson-dates.js from git history. Do not edit by hand.\n// The date each lesson's text last changed. The app shows it and flags lessons older than 12 months.\nwindow.INFRA = window.INFRA || { lessons: [], glossary: [], scenarios: [] };\nINFRA.lessonDates = ${JSON.stringify(sorted, null, 0).replace(/,"/g, ',\n  "').replace(/^\{/, "{\n  ").replace(/\}$/, "\n}")};\n`;

if (process.argv.includes("--check")) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (cur !== body) { console.log("content/lesson-dates.js is out of date: run node tools/lesson-dates.js"); process.exit(1); }
  console.log("lesson dates OK"); process.exit(0);
}
fs.writeFileSync(OUT, body);
console.log(`wrote content/lesson-dates.js (${Object.keys(sorted).length} lessons)`);
